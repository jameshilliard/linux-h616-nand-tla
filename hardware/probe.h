#ifndef NFC_PROBE_H
#define NFC_PROBE_H
#include <linux/types.h>
#include <linux/ioctl.h>

enum {
	PROBE_INFO,
	PROBE_READ,
	PROBE_COUNT,
	PROBE_BANKS,
	PROBE_ERASE,
	PROBE_PROGRAM,
	PROBE_ECC_READ,
	PROBE_ECC_WRITE,
	PROBE_PIO_ECC_READ,
	PROBE_EVENTS,
	PROBE_NATIVE_READ,
	PROBE_NATIVE_WRITE,
	PROBE_NATIVE_SUBREAD,
	PROBE_NATIVE_SUBWRITE,
	PROBE_NATIVE_OOB_READ,
	PROBE_NATIVE_OOB_WRITE,
	PROBE_NATIVE_RAW_READ,
	PROBE_NATIVE_RAW_WRITE,
	PROBE_CODEWORD_READ,
	PROBE_TRANSITIONS,
	PROBE_RECOVERY,
	PROBE_ACTUAL_SUBREAD,
	/* 22/23 are userspace MEMREAD/MEMWRITE transport operations. */
	PROBE_RECOVERY_SNAPSHOT = 24,
	PROBE_MASKED_NATIVE_READ,
	PROBE_RESET_FOLLOWUP,
	PROBE_ABORT_NATIVE_READ
};
#define PROBE_RANDOM 1
#define PROBE_RESEED 2
#define PROBE_PAGE_RANDOM 4
#define PROBE_PIPELINE 8
#define PROBE_WORD_READ 16
#define PROBE_MSB 32
#define PROBE_TOGGLE 64
#define PROBE_RAW_SIZE 2176
struct probe_request {
	__u32 op, page, column, length, chunk, seed, flags;
	__s32 result;
	__u32 regs[16];
	__u8 data[PROBE_RAW_SIZE];
};
#define PROBE_IOC _IOWR('N', 0x61, struct probe_request)
#endif
