"""Compose exact randomizer state with captures and older-NFC uncertainty.

Offline: no board access. BSP audit downloads are opt-in and hash checked.
Passing an uncertainty envelope does not identify which alternative is silicon.
"""
import argparse
import hashlib
import json
from pathlib import Path
import tempfile

from codec_oracle import encode, scramble
from randomizer_cases import freeze
from randomizer_controller import (Controller, bsp_contract_profile, command, config,
                                   measured_profile, profile)
import run as tlc

HERE = Path(__file__).resolve().parent
MODULE = 'NandRandomizerController'
SPEC = dict(invariants=['ExactState', 'ObservedBytes', 'FailedReadNotPublished', 'Bounds'],
            actions=['Config', 'Reset', 'Start', 'Byte', 'Finish', 'Abort', 'End'],
            dependencies=['NandRandomizerMath'])


def digest(data):
    return hashlib.sha256(data).hexdigest()


def logical(index, size=2176):
    return bytes((i * 37 + (i >> 8) * 13 + index * 7) & 255 for i in range(size))


def cfg(seed, **kw):
    return dict(op='config', value=config(seed, **kw))


def events_for_stream(row, read=True, toggle=False):
    seed, flags = row['seed'], row['flags']
    col, size = row.get('column', 0), row.get('length', 4 * row.get('chunk', 31))
    chunk = row['chunk'] if toggle else 31
    data = logical(0)[col:col + size]
    page, msb = bool(flags & 4), bool(flags & 32)
    events = [cfg(seed, page=page, msb=msb)]
    expected = bytes.fromhex(row['data_hex']) if toggle else None
    for index, offset in enumerate(range(0, size, chunk)):
        if toggle and index in (1, 2):
            events.append(cfg(seed, page=page, msb=msb, enabled=index == 2))
        events.append(command(data[offset:offset + chunk], read=read, column=col + offset,
                              expected=None if expected is None else expected[offset:offset + chunk]))
    return events


def native_events(index, seed):
    """Physical ECC bus stream, not the main-then-OOB memory buffer layout."""
    data = logical(index)
    units, offset = [], 2048
    for step, user in enumerate((8, 0)):
        payload = data[step * 1024:(step + 1) * 1024] + data[offset:offset + user]
        units.append(payload + encode(payload, 32))
        offset += user + 56
    expected = b''.join(scramble(unit, seed) for unit in units)
    events = [cfg(seed), command(b''.join(units), read=False, kind='PAGE',
                                  boundaries=(len(units[0]),), expected=expected),
              cfg(seed, enabled=False), cfg(seed),
              command(data[offset:], read=False, expected=scramble(data[offset:], seed))]
    return events, units


def replay_h616(capture, seeds):
    """New stateful implementation versus immutable captures, not boolean flags."""
    checks = 0
    for row in capture['streams']['rows']:
        result = b''.join(Controller(measured_profile()).run(events_for_stream(row)))
        assert digest(result) == row['sha256']
        checks += 1
    for read, rows in ((True, capture['streams']['transitions']),
                       (False, capture['transitionwrites']['rows'])):
        for row in rows:
            result = b''.join(Controller(measured_profile()).run(events_for_stream(row, read, True)))
            assert result.hex() == row['data_hex']
            checks += 1
    for row in capture['native']['rows']:
        events, units = native_events(row['index'], seeds[row['index']])
        codewords, tail = Controller(measured_profile()).run(events)
        first = codewords[:len(units[0])]
        second = codewords[len(units[0]):]
        physical = first[:1024] + second[:1024] + first[1024:] + second[1024:] + tail
        assert digest(physical) == row['physical_sha256']
        checks += 1
    assert checks == 3184
    return checks


def build_cases(capture, seeds):
    cases = []

    def add(name, events, p=None, mutation='none', expected=None, kind='positive',
            initial=(0,), validity=(False,)):
        cases.append(dict(name='controller-' + name, module=MODULE, kind=kind,
                          expected=expected, constants=dict(Events=freeze(events),
                          Profile=profile('h616') if p is None else p,
                          InitialStates=set(initial), InitialValidity=set(validity),
                          Mutation=mutation)))

    # Actual captured bytes, not output generated by this hardware model.
    for read, rows in ((True, capture['streams']['transitions']),
                       (False, capture['transitionwrites']['rows'])):
        for row in rows:
            if row['seed'] != seeds[0] or row['chunk'] not in (4, 31, 513):
                continue
            events = events_for_stream(row, read, True)
            name = f'capture-{read}-{bool(row["flags"] & 4)}-{row["chunk"]}'
            add(name, events)
            if read and row['flags'] & 4 and row['chunk'] == 31:
                for change in ('register-is-state', 'reload-on-enable', 'advance-disabled',
                               'tail-freezes-state', 'randomize-tail'):
                    add(change, events, mutation=change, expected='ObservedBytes', kind='mutation')
            if read and not row['flags'] & 4 and row['chunk'] == 4:
                add('continue-command', events, mutation='continue-command',
                    expected='ObservedBytes', kind='mutation')

    # Byte-order and column checks use independent codec bytes, whose complete
    # hashes above have been compared to the recorded hardware read matrix.
    for page in (False, True):
        row = next(r for r in capture['streams']['rows'] if r['seed'] == seeds[0]
                   and r['column'] == 1 and r['flags'] == (37 if page else 33))
        data = logical(0)[1:74]
        key = scramble(bytes(73), seeds[0])
        expected = bytearray()
        for offset in range(0, 73, 31):
            part = data[offset:offset + 31]
            mask = key[offset:offset + len(part)] if page else key[:len(part)]
            mask = [int(f'{v:08b}'[::-1], 2) for v in mask]
            if len(part) % 4:
                mask[-1] = 0
            expected.extend(x ^ y for x, y in zip(part, mask))
        assert digest(expected) == row['sha256']
        events = events_for_stream(row)
        pos = 0
        for event in events:
            if event['op'] == 'command':
                n = len(event['input'])
                event.update(check=True, expected=tuple(expected[pos:pos + n]))
                pos += n
        add('msb-column-' + str(page), events)
        if not page:
            for change in ('ignore-msb', 'column-is-phase'):
                add(change, events, mutation=change, expected='ObservedBytes', kind='mutation')

    for index in (0, 63):
        events, _ = native_events(index, seeds[index])
        add('native-page-' + str(index), events)
        if index == 0:
            add('continue-codeword', events, mutation='continue-codeword',
                expected='ObservedBytes', kind='mutation')

    # BSP fixed USER_DATA signatures independently corroborate recurrence and
    # 15-bit warm-up through 1024 bytes; other bytes are oracle expectations.
    for soc in ('a10', 'a20', 'a23', 'a33'):
        for page, signature in ((0, bytes.fromhex('0a53b8c2')),
                                (127, bytes.fromhex('3243aa4e'))):
            seed = seeds[page]
            plain = bytes([255]) * 1084
            encoded = scramble(plain, seed)
            assert encoded[1024:1028] == signature
            events = [cfg(seed, legacy=True),
                      command(plain * 2, kind='PAGE', boundaries=(1084,), expected=encoded * 2),
                      cfg(seed, legacy=True, enabled=False),
                      command(bytes([255]) * 4, expected=bytes([255]) * 4)]
            add('bsp-signature-' + soc + '-' + str(page), events, bsp_contract_profile(soc))

    # An uncertainty envelope permits alternate NORMAL rules on old NFCs.
    # Only documented byte bypass when disabled and exact arithmetic are
    # unconditional here; undocumented stream identities are not asserted.
    for soc in ('a10', 'a20', 'a23', 'a33'):
        events = []
        for page in ((False,) if soc in ('a10', 'a20', 'a23') else (False, True)):
            for read in (False, True):
                events += [cfg(seeds[0], legacy=True, page=page),
                           command(bytes(range(5)), read=read),
                           cfg(seeds[1], legacy=True, page=page, msb=True),
                           command(bytes(range(4)), read=read, kind='ECC'),
                           command(bytes(range(8)), read=read, kind='PAGE', boundaries=(4,)),
                           cfg(seeds[1], legacy=True, page=page, msb=True, enabled=False),
                           command(b'plain', read=read, expected=b'plain')]
        add('older-envelope-' + soc, events, profile(soc))

    # Faults can leave an internal phase even if software-visible registers
    # have reset. Fresh block-mode ECC/PAGE launch must use the new chip seed.
    for soc in ('h616', 'a10', 'a20', 'a23', 'a33'):
        old = soc != 'h616'
        for read in (False, True):
            events = [cfg(seeds[0], legacy=old),
                      command(b'abcdef', kind='ECC', read=read, aborts=range(7)),
                      dict(op='nand-reset', value=0), dict(op='soft-reset', value=0),
                      dict(op='select', value=1), dict(op='bus-reset', value=0),
                      cfg(seeds[127], legacy=old, msb=True)]
            key = scramble(bytes(8), seeds[127])
            expected = bytes(v ^ int(f'{k:08b}'[::-1], 2) for v, k in zip(b'new-chip', key))
            events += [command(b'new-chip', kind='PAGE', read=read, expected=expected),
                       cfg(seeds[127], legacy=old, enabled=False),
                       command(b'plain', expected=b'plain')]
            add(f'abort-reuse-{soc}-{read}', events, bsp_contract_profile(soc),
                initial=(0, 1, 32767), validity=(False, True))
            if soc == 'h616' and read:
                add('copy-failed-read', events, mutation='copy-failed-read',
                    expected='FailedReadNotPublished', kind='mutation')

    # Composed command kinds, not just isolated commands. Short abstract
    # codewords keep the transition envelope tractable; full physical units
    # are checked above. Only block-mode ECC/PAGE has a fixed reload contract.
    for soc in ('h616', 'a10', 'a20', 'a23', 'a33'):
        old = soc != 'h616'
        for read in (False, True):
            data = b'01234567'
            block = scramble(data[:4], seeds[1]) + scramble(data[4:], seeds[1])
            events = [cfg(seeds[0], legacy=old), command(b'abcde', read=read),
                      cfg(seeds[1], legacy=old),
                      command(data, kind='ECC', read=read, boundaries=(4,), expected=block),
                      command(b'next', read=read)]
            if soc in ('h616', 'a33'):
                events += [cfg(seeds[1], legacy=old, page=True),
                           command(data, kind='PAGE', read=read, boundaries=(4,)),
                           command(b'tail!', read=read)]
            events += [cfg(seeds[1], legacy=old, enabled=False),
                       command(b'plain', kind='ECC', read=read, expected=b'plain'),
                       dict(op='select', value=1), cfg(seeds[127], legacy=old),
                       command(data, kind='PAGE', read=read,
                               expected=scramble(data, seeds[127]))]
            add(f'mixed-commands-{soc}-{read}', events, bsp_contract_profile(soc),
                initial=(0, 1, 32767), validity=(False, True))

    # Deliberately ask for guarantees not established by the public evidence.
    # Counterexamples are uncertainty witnesses, not newly discovered bugs.
    for change in ('seed', 'mode', 'select', 'nand-reset'):
        events = [cfg(seeds[0], page=True), command(b'abcd')]
        if change == 'seed':
            events += [cfg(seeds[1], page=True)]
            seed = seeds[1]
        elif change == 'mode':
            events += [cfg(seeds[0], page=True, msb=True)]
            seed = seeds[0]
        else:
            events += [dict(op=change, value=1)]
            seed = seeds[0]
        key = scramble(bytes(4), seed)
        if change == 'mode':
            key = bytes(int(f'{v:08b}'[::-1], 2) for v in key)
        events += [command(b'next', expected=bytes(a ^ b for a, b in zip(b'next', key)))]
        add('assumption-' + change + '-rewinds', events, expected='ObservedBytes', kind='assumption')
    for soc in ('a10', 'a23'):
        data = b'abcdefgh'
        events = [cfg(seeds[0], legacy=True),
                  command(data[:4], expected=scramble(data[:4], seeds[0])),
                  command(data[4:], expected=scramble(data[4:], seeds[0]))]
        add('assumption-' + soc + '-normal-restarts', events, profile(soc),
            expected='ObservedBytes', kind='assumption')
        events = [cfg(seeds[0], legacy=True),
                  command(data, kind='PAGE', boundaries=(4,),
                          expected=scramble(data[:4], seeds[0]) + scramble(data[4:], seeds[0]))]
        add('assumption-' + soc + '-codeword-restarts', events, profile(soc),
            expected='ObservedBytes', kind='assumption')
    return cases


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source-only', action='store_true', help='replay evidence without TLC')
    p.add_argument('--download', action='store_true')
    p.add_argument('--case', default='')
    p.add_argument('--timeout', type=int, default=180)
    args = p.parse_args()
    if __debug__ is False:
        p.error('validation requires assertions enabled')
    # Immutable captures, including the original native-path source identity.
    raw = (HERE / 'hardware/h616-extended-20261104.json').read_bytes()
    assert digest(raw) == '03000e53c9b36740632ecfecacbc5a90d17ed8dfab13625d713935caa086aa0a'
    capture = json.loads(raw)
    from run_randomizer import seed_tables
    seeds = seed_tables()['PageSeeds']
    count = replay_h616(capture, seeds)
    cases = build_cases(capture, seeds)
    (HERE / 'results').mkdir(exist_ok=True)
    out = Path(tempfile.mkdtemp(prefix='randomizer-hardware-', dir=HERE / 'results'))
    from bsp_randomizer_evidence import audit
    bsp = audit(out, seeds, args.download)
    metadata = dict(capture_sha256=digest(raw), captures_replayed=count,
                    evidence='Measured H616; older-NFC unknowns are nondeterministic alternatives',
                    model_sha256=digest((HERE / 'models' / (MODULE + '.tla')).read_bytes()),
                    runner_sha256=digest(Path(__file__).read_bytes()),
                    simulator_sha256=digest((HERE / 'randomizer_controller.py').read_bytes()),
                    bsp=bsp, source_only=args.source_only)
    (out / 'inputs.json').write_text(json.dumps(metadata, indent=2) + '\n')
    print(f'{count} exact H616 capture comparisons passed; {len(cases)} model cases prepared', flush=True)
    result = 0
    if not args.source_only:
        argv = ['--case', args.case, '--timeout', str(args.timeout)]
        if args.download:
            argv.append('--download')
        result = tlc.main(argv, cases=cases, modules={MODULE: SPEC}, metadata=metadata)
    (out / 'summary.json').write_text(json.dumps(dict(metadata, passed=result == 0), indent=2) + '\n')
    print('Logs:', out)
    return result


if __name__ == '__main__':
    raise SystemExit(main())
